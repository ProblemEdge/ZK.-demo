import { skillInput } from "./types";
import { Output } from "../../shared/schema";
import { promises as fs } from "fs";
import * as path from "path";

export async function skillHandler(
  input: unknown
): Promise<Output> {
  const parsed = skillInput.parse(input);
  const root = process.cwd();
  const skillsDir = path.join(root, "skills");
  const skillDir = path.join(skillsDir, parsed.name);

  try {
    await fs.mkdir(skillDir, { recursive: true });

    const lang = parsed.lang ?? "ts";
    const desc = parsed.desc ?? "";

    const skillMd = `---\nname: ${parsed.name}\ndescription: ${desc}\nlanguage: ${lang}\n---\n\n# ${parsed.name}\n\nGenerated by skill-factory.\n`;

    await fs.writeFile(path.join(skillDir, "SKILL.md"), skillMd, "utf8");

    if (lang === "ts") {
      const main = `#!/usr/bin/env node\n\nconsole.log('Hello from ${parsed.name} (TypeScript)');\n`;
      await fs.writeFile(path.join(skillDir, "main.ts"), main, "utf8");
    } else if (lang === "rust") {
      const main = `fn main() {\n    println!("Hello from ${parsed.name} (Rust)");\n}\n`;
      await fs.writeFile(path.join(skillDir, "main.rs"), main, "utf8");
    } else {
      const main = `#!/usr/bin/env python3\nprint('Hello from ${parsed.name} (Python)')\n`;
      await fs.writeFile(path.join(skillDir, "main.py"), main, "utf8");
    }

    return { error: null, data: `Created skill at skills/${parsed.name}` };
  } catch (err: unknown) {
    return { error: String(err), data: null };
  }
}
